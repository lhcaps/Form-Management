function readCompiled(code) {
  const p = `${COMPILED_DIR}/${code}.compiled.json`;
  if (!existsSync(p)) return null;
  return JSON.parse(readFileSync(p, "utf8"));
}

function readProfile(code) {
  const p = `${PROFILES_DIR}/bm${code.slice(3)}-runtime-ux-profile.ts`;
  if (!existsSync(p)) return null;
  return readFileSync(p, "utf8");
}

function detectStaleInDemoBlock(src) {
  if (!src) return [];
  const demoStart = src.indexOf("demo:");
  if (demoStart < 0) return [];
  const slice = src.slice(demoStart, demoStart + 4096);
  const hits = [];
  for (const token of STALE_TOKENS) {
    if (slice.includes(token)) hits.push(token);
  }
  return hits;
}

function parseSectionsCount(src) {
  if (!src) return 0;
  // Accept either inline `sections: [...]` (generated) or `const X = [...]`
  // (curated, e.g. BM-001 uses `const BM001_SECTIONS = [...]`).
  const inline = src.match(/sections\s*:\s*\[([\s\S]*?)\]\s*[,}]/);
  const slice = inline ? inline[1] : "";
  const idMatches = slice.match(/sectionId\s*:\s*"/g) || slice.match(/id\s*:\s*"section-/g);
  if (idMatches && idMatches.length > 0) return idMatches.length;
  // Fallback: any constant that mentions "section-" ids.
  const idsInSource = src.match(/"section-[a-z0-9-]+"/g);
  return idsInSource ? idsInSource.length : 0;
}

function parseFieldsCount(src) {
  if (!src) return 0;
  // Curated: `const X = { "key.path": { ... }, ... }` — count quoted key strings
  // with a dot.
  const dotKeyMatches = src.match(/"[a-zA-Z]+\.[a-zA-Z0-9]+"\s*:\s*\{/g);
  if (dotKeyMatches && dotKeyMatches.length > 0) return dotKeyMatches.length;
  // Generated: `fields: [...]` array with id overrides.
  const inline = src.match(/fields\s*:\s*\[([\s\S]*?)\]\s*\}/);
  const slice = inline ? inline[1] : "";
  const idMatches = slice.match(/key\s*:\s*"/g);
  return idMatches ? idMatches.length : 0;
}

function isRegisteredInIndex(code) {
  const idx = existsSync(INDEX_FILE) ? readFileSync(INDEX_FILE, "utf8") : "";
  const file = `bm${code.slice(3)}-runtime-ux-profile`;
  return idx.includes(`./${file}`);
}

function lockedExists(code) {
  // Filenames look like: BM-001__f4c2aa3682d3.contract.locked.json
  if (!existsSync(LOCKED_DIR)) return false;
  try {
    const entries = readdirSync(LOCKED_DIR);
    const needle = `${code}__`;
    return entries.some((name) => name.startsWith(needle) && name.endsWith(".contract.locked.json"));
  } catch {
    return false;
  }
}

function main() {
  const results = [];
  for (const code of CURATED_CODES) {
    const compiled = readCompiled(code);
    const profileSrc = readProfile(code);
    const staleTokens = detectStaleInDemoBlock(profileSrc);
    const sectionsCount = parseSectionsCount(profileSrc);
    const fieldsCount = parseFieldsCount(profileSrc);
    const registered = isRegisteredInIndex(code);
    const locked = lockedExists(code);

    results.push({
      templateCode: code,
      lockedExists: locked,
      compiledExists: !!compiled,
      runtimeUxProfileExists: !!profileSrc,
      runtimeUxProfileRegistered: registered,
      sectionCount: sectionsCount,
      fieldCount: fieldsCount,
      staleTokensInDemoBlock: staleTokens,
      passes:
        locked &&
        !!compiled &&
        !!profileSrc &&
        registered &&
        sectionsCount > 0 &&
        staleTokens.length === 0,
    });
  }

  const summary = {
    snapshotDate: new Date().toISOString(),
    codes: results,
    allPass: results.every((r) => r.passes),
  };

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(`${OUT_DIR}/QLLAW_CURATED_RENDER_SMOKE.latest.json`, JSON.stringify(summary, null, 2));

  const lines = [];
  lines.push("# QLLAW Curated Render Smoke — latest");
  lines.push("");
  lines.push(`> **Generated**: ${summary.snapshotDate}`);
  lines.push(`> **Codes**: ${CURATED_CODES.join(", ")}`);
  lines.push(`> **All pass**: ${summary.allPass}`);
  lines.push("");
  lines.push("| Code | Locked | Compiled | Profile | Registered | Sections | Fields | Stale demo | Pass |");
  lines.push("|---|---|---|---|---|---|---|---|---|");
  for (const r of summary.codes) {
    lines.push(
      `| ${r.templateCode} | ${r.lockedExists} | ${r.compiledExists} | ${r.runtimeUxProfileExists} | ${r.runtimeUxProfileRegistered} | ${r.sectionCount} | ${r.fieldCount} | ${r.staleTokensInDemoBlock.length === 0 ? "—" : r.staleTokensInDemoBlock.join(",")} | ${r.passes} |`,
    );
  }
  lines.push("");
  writeFileSync(`${OUT_DIR}/QLLAW_CURATED_RENDER_SMOKE.latest.md`, lines.join("\n") + "\n");

  console.log(JSON.stringify(summary, null, 2));
  if (!summary.allPass) process.exitCode = 1;
}

main();
