async function main() {
  const candidates = readJson(CANDIDATES, "candidates artifact");
  if (candidates.status === "PASS_INVENTORY_ONLY") {
    fail("candidates status is PASS_INVENTORY_ONLY — nothing to smoke");
  }
  const codes = candidates.selectedCodes ?? [];
  if (codes.length === 0) fail("zero candidates to smoke");

  // Ensure Clerk storageState exists.
  const storageState = `${ROOT}/playwright/.clerk/admin.json`;
  if (!existsSync(storageState)) {
    fail(`NEED_USER_DECISION: Clerk storageState missing at ${storageState}`);
  }
  const stat = readFileSync;
  const ssBytes = readFileSync(storageState);
  const storageStateBytes = ssBytes.length;
  if (storageStateBytes < 200) {
    fail(`NEED_USER_DECISION: Clerk storageState at ${storageState} is suspiciously small (${storageStateBytes}B). Refresh via tests/e2e/global.setup.ts.`);
  }

  // Emit codes.json + dynamic spec.
  mkdirSync(TMP_DIR, { recursive: true });
  writeFileSync(TMP_CODES_JSON, JSON.stringify(codes, null, 2));
  const codesLiteral = JSON.stringify(codes);
  const specSource = buildSpec(codesLiteral);
  writeFileSync(TMP_SPEC, specSource);

  // Wait for web dev server. PLAYWRIGHT_BASE_URL or default http://localhost:3000.
  const baseUrl = process.env.PLAYWRIGHT_BASE_URL ?? "http://localhost:3000";
  const apiUrl = "http://localhost:3001";
  console.log(`[browser-visibility] base URL: ${baseUrl}`);
  const apiOk = await waitFor(`${apiUrl}/api/v1/health`, "api /api/v1/health", 180_000);
  if (!apiOk) {
    fail(`NEED_USER_DECISION: API did not become ready at ${apiUrl}/api/v1/health within 180s. Start the dev server first.`);
  }
  const webOk = await waitFor(`${baseUrl}/healthz`, "web /healthz", 180_000);
  if (!webOk) {
    fail(`NEED_USER_DECISION: Web did not become ready at ${baseUrl}/healthz within 180s.`);
  }

  // Run Playwright. Use existing playwright.config.ts.
  // --workers=1 keeps auth stable; --reporter=json writes the raw output.
  const baseArgs = [
    "playwright", "test",
    "--config=playwright.config.ts",
    "--project=authenticated chromium",
    "tests/e2e/source-render-only-browser-visibility.auth.spec.ts",
    "--workers=1",
    "--reporter=json",
  ];

  function runPlaywright(args, rawOutPath) {
    // On Windows, use cmd.exe /c so that .cmd shims resolve correctly.
    const isWin = process.platform === "win32";
    const cmd = isWin ? "cmd.exe" : "npx";
    const cmdArgs = isWin
      ? ["/c", "npx", ...args]
      : args;
    console.log(`[browser-visibility] running: ${cmd} ${cmdArgs.join(" ")}`);
    const r = spawnSync(cmd, cmdArgs, {
      cwd: ROOT,
      env: process.env,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      windowsHide: true,
    });
    if (r.stdout && r.stdout.length > 0) writeFileSync(rawOutPath, r.stdout);
    else if (r.stderr && r.stderr.length > 0) writeFileSync(rawOutPath, r.stderr);
    else return { run: null, status: r.status, stdout: "", stderr: "" };
    const run = loadPlaywrightRun(rawOutPath);
    return { run, status: r.status, stdout: r.stdout ?? "", stderr: r.stderr ?? "" };
  }

  const TMP_RAW_MAIN = `${TMP_DIR}/raw.main.json`;
  const TMP_RAW_RERUN = `${TMP_DIR}/raw.rerun.json`;
  const mainResult = runPlaywright(baseArgs, TMP_RAW_MAIN);
  if (mainResult.status !== 0 && mainResult.status !== 1) {
    console.warn(`[browser-visibility] Playwright main exited with status ${mainResult.status}; continuing with parsing.`);
  }
  if (!mainResult.run || !mainResult.run.byCode || mainResult.run.byCode.size === 0) {
    fail(`FATAL: no Playwright run loaded from ${TMP_RAW_MAIN}: ${mainResult.run?.error ?? "unknown"}`);
  }

  // Identify throttle-classified failures for cooldown rerun.
  const throttledCodes = [];
  for (const code of codes) {
    const row = mainResult.run.byCode.get(code);
    if (!row || row.status === "passed") continue;
    const cls = classifyFailure(row.errorMessage, row.durationMs);
    if (cls === "THROTTLED_TRANSIENT") throttledCodes.push(code);
  }

  let rerunResult = null;
  if (throttledCodes.length > 0) {
    console.log(`[browser-visibility] cooldown 30s before rerun of ${throttledCodes.length} throttle-transient codes...`);
    await new Promise((r) => setTimeout(r, 30_000));

    // Regenerate the spec with only the rerun codes.
    const rerunLiteral = JSON.stringify(throttledCodes);
    const rerunSpec = buildSpec(rerunLiteral);
    writeFileSync(TMP_SPEC, rerunSpec);

    rerunResult = runPlaywright(baseArgs, TMP_RAW_RERUN);
    if (rerunResult.status !== 0 && rerunResult.status !== 1) {
      console.warn(`[browser-visibility] Playwright rerun exited with status ${rerunResult.status}; continuing with parsing.`);
    }
  }

  // Restore the full-code spec for re-runs / debugging.
  const fullSpec = buildSpec(JSON.stringify(codes));
  writeFileSync(TMP_SPEC, fullSpec);

  const run = mainResult.run;
  const rerunByCode = rerunResult?.run?.byCode ?? new Map();

  // Build per-form results, preferring rerun evidence for throttle-transient failures.
  const perForm = [];
  let passed = 0;
  let failed = 0;
  let skipped = 0;
  const rerunOverrides = [];
  for (const code of codes) {
    const row = run.byCode.get(code);
    if (!row) {
      failed++;
      perForm.push({
        code,
        url: `/templates/${code}`,
        browserVerified: false,
        status: "NOT_RUN",
        fieldsVisible: false,
        labelsOrSectionsVisible: false,
        stayedOnTemplatesRoute: false,
        routedToDocuments: false,
        historyUiVisible: false,
        fatalError: true,
        authRequired: true,
        authUsed: true,
        failureReason: "No Playwright result captured for this code",
        durationMs: null,
        evidenceSource: "main",
        mainRunStatus: null,
        rerunStatus: null,
      });
      continue;
    }
    let effectiveRow = row;
    let evidenceSource = "main";
    const mainFailed = row.status !== "passed";
    const mainClass = mainFailed ? classifyFailure(row.errorMessage, row.durationMs) : null;
    const rerunRow = rerunByCode.get(code);
    if (mainFailed && mainClass === "THROTTLED_TRANSIENT" && rerunRow && rerunRow.status === "passed") {
      effectiveRow = rerunRow;
      evidenceSource = "rerun";
      rerunOverrides.push(code);
    }
    const ok = effectiveRow.status === "passed";
    if (ok) passed++;
    else failed++;

    const failureClass = ok ? null : classifyFailure(effectiveRow.errorMessage, effectiveRow.durationMs);
    perForm.push({
      code,
      url: `/templates/${code}`,
      browserVerified: ok,
      status: ok ? "PASS" : "FAIL",
      fieldsVisible: ok,
      labelsOrSectionsVisible: ok,
      stayedOnTemplatesRoute: ok,
      routedToDocuments: !ok && /documents/i.test(effectiveRow.errorMessage ?? ""),
      historyUiVisible: !ok && /Lịch sử xử lý/i.test(effectiveRow.errorMessage ?? ""),
      fatalError: !ok,
      authRequired: true,
      authUsed: true,
      failureClass,
      failureReason: ok ? null : `${failureClass}: ${effectiveRow.errorMessage ?? ""}`,
      durationMs: effectiveRow.durationMs ?? null,
      evidenceSource,
      mainRunStatus: row.status,
      rerunStatus: rerunRow?.status ?? null,
      mainRunFailureClass: mainClass,
    });
  }
  skipped = 0;

  const status = failed === 0 && passed === codes.length ? "PASS" :
    (passed === 0 ? "FAIL" : "PARTIAL");

  const statusNote = status === "PASS"
    ? `All ${codes.length} source/render-only forms passed authenticated Playwright browser-visibility smoke (${rerunOverrides.length > 0 ? `main + ${rerunOverrides.length} cooldown rerun override${rerunOverrides.length === 1 ? "" : "s"} for THROTTLED_TRANSIENT forms` : "single main run"}). No demo / preview / DOCX / fidelity phase was run. Existing 201 evidence (37+20+20+20+20+20+24) remains untouched.`
    : `${passed}/${codes.length} passed; ${failed} failed. See per-form results.`;

  const snapshotDate = new Date().toISOString();
  const artifact = {
    snapshotDate,
    status,
    statusNote,
    sourceRenderStatus: "PASS",
    browserVisibilityStatus: failed === 0 ? "PASS" : "PARTIAL",
    demoClickStatus: "NOT_RUN",
    previewClickStatus: "NOT_RUN",
    docxDownloadStatus: "NOT_RUN",
    machineCheckableFidelityStatus: "NOT_RUN",
    visualPdfReviewStatus: "NOT_RUN",
    fidelityCompleteClaimed: false,
    totalForms: codes.length,
    formsVisibilitySmoked: codes.length,
    formsVisibilityPassed: passed,
    formsVisibilityFailed: failed,
    formsVisibilitySkipped: skipped,
    authStrategy: "clerk_ticket_storage_state",
    qlvSessionUsedForWebRoute: false,
    generatedAt: snapshotDate,
    codes,
    perForm,
    existing201EvidencePreserved: true,
    manualReviewRequired: false,
    formFlightRuntimeReadyPromoted: 0,
    playwrightStats: run.stats ?? null,
    rerunOverrides,
    rerunCodes: rerunOverrides,
    rerunCount: rerunOverrides.length,
    // Hard refusals
    sourceDocxMutated: false,
    normalizedDocxMutated: false,
    lockedContractsMutated: false,
    compiledContractsMutated: false,
    dbMutated: false,
    prismaSchemaMutated: false,
    migrationsCreated: false,
    publicApiRoutePathsChanged: false,
    commitCreated: false,
    gitPushed: false,
    filesStaged: false,
    envValuesLogged: false,
    playwrightStorageStateCommitted: false,
    newFrameworkCreated: false,
    notes: [
      "PHASE 2 source/render-only browser-visibility smoke — local-only.",
      "Spec asserts authenticated URL is not sign-in/sign-up, BM code or title visible, at least one h3 section heading visible, at least one input/textarea/select visible, 'Xem trước bản in' button visible, 'Không tìm thấy trang' boundary absent, no 'Lịch sử xử lý' history UI, no fatal console/page errors, and the URL stays on /templates/<code> (does NOT navigate to /documents/<id>).",
      "Spec does NOT click preview, does NOT click demo, does NOT exercise the preview-session API, does NOT download DOCX.",
      "Existing 201 evidence (curated 37 + Batch 3 + Batch 4 + Batch 5/6/7/8/9 source-render + remaining-source-render sweep) remains untouched.",
      "No FIDELITY_COMPLETE_EVIDENCED claim is set.",
      "FormFlight runtimeReady allowlist remains BM-001 + BM-171 only.",
      "Demo-click / preview-click / DOCX download / fidelity phases for source/render-only sweep run in separate follow-up phases.",
    ],
    remainingRisks: [
      "Source/render-only demo-click not run",
      "Source/render-only preview-click not run",
      "Source/render-only DOCX download not run",
      "Source/render-only fidelity audit not run",
      "Existing 201 still require visual/PDF review before fidelityComplete",
      "FormFlight runtimeReady allowlist remains BM-001 + BM-171 only",
      "FIDELITY_COMPLETE_EVIDENCED not claimed",
      "12 PARTIAL holdouts remain INPUT_CONNECTED_PARTIAL by design",
    ],
  };

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(ARTIFACT, JSON.stringify(artifact, null, 2));
  writeFileSync(ARTIFACT_MD, renderMd(artifact));
  writeFileSync(TMP_PARSED, JSON.stringify({
    snapshotDate,
    stats: run.stats,
    codes: perForm,
  }, null, 2));

  console.log(JSON.stringify({
    ok: status !== "FAIL",
    status,
    statusNote,
    totalForms: codes.length,
    formsVisibilitySmoked: codes.length,
    formsVisibilityPassed: passed,
    formsVisibilityFailed: failed,
    formsVisibilitySkipped: skipped,
    rerunCount: rerunOverrides.length,
    rerunCodes: rerunOverrides,
    authStrategy: "clerk_ticket_storage_state",
    artifact: ARTIFACT.replace(`${ROOT}/`, ""),
    parsedPlaywrightJson: TMP_PARSED.replace(`${ROOT}/`, ""),
    generatedSpec: TMP_SPEC.replace(`${ROOT}/`, ""),
  }, null, 2));

  if (status === "FAIL") process.exit(2);
}

