// The spec is built line-by-line so that we never need to escape
// backticks or `${` inside a JS template literal — we just want plain
// template literal source written to the file.
function buildSpec(codesLiteral) {
  const lines = [];
  lines.push("/**");
  lines.push(" * GENERATED by scripts/audit/browser-visibility-source-render-only.mjs (PHASE 2).");
  lines.push(" *");
  lines.push(" * Authenticated routing/visibility smoke for source/render-only INPUT_CONNECTED_PASS");
  lines.push(" * forms that have not yet had browser evidence. Codes are emitted from");
  lines.push(" * docs/audit/unified-bm-workspace/QLLAW_SOURCE_RENDER_ONLY_BROWSER_VISIBILITY_CANDIDATES.latest.json");
  lines.push(" * (data-driven; no hardcoded list).");
  lines.push(" *");
  lines.push(" * Asserts per code:");
  lines.push(" *   - not redirected to /sign-in or /sign-up");
  lines.push(" *   - page URL stays on /templates/<code> (does NOT redirect to /documents/...)");
  lines.push(" *   - \"BM-NNN\" is visible somewhere on the page");
  lines.push(" *   - at least one <h3> section heading is visible");
  lines.push(" *   - at least one <input> or <textarea> or <select> is visible");
  lines.push(" *   - \"Xem trước bản in\" button is visible");
  lines.push(" *   - page does not show the \"Không tìm thấy trang\" boundary");
  lines.push(" *   - no \"Lịch sử xử lý\" history UI visible");
  lines.push(" *   - no fatal console errors");
  lines.push(" *");
  lines.push(" * Does NOT click preview, does NOT click demo, does NOT exercise the");
  lines.push(" * preview-session API, does NOT download DOCX.");
  lines.push(" */");
  lines.push("import { expect, test } from \"@playwright/test\";");
  lines.push("");
  lines.push(`const CODES: string[] = ${codesLiteral};`);
  lines.push("");
  lines.push("test.describe(\"Source/Render-Only Browser Visibility Smoke (auth)\", () => {");
  lines.push("  for (const templateCode of CODES) {");
  lines.push("    test(`${templateCode} loads authenticated with runtime-ux shell`, async ({ page }) => {");
  lines.push("      const consoleErrors: string[] = [];");
  lines.push("      const pageErrors: string[] = [];");
  lines.push("");
  lines.push("      page.on(\"console\", (msg) => {");
  lines.push("        if (msg.type() === \"error\") consoleErrors.push(msg.text());");
  lines.push("      });");
  lines.push("      page.on(\"pageerror\", (err) => {");
  lines.push("        pageErrors.push(String(err));");
  lines.push("      });");
  lines.push("");
  lines.push("      await page.goto(`/templates/${templateCode}`);");
  lines.push("");
  lines.push("      await expect(page).not.toHaveURL(/sign-in|sign-up|\\/documents\\//, {");
  lines.push("        timeout: 20_000,");
  lines.push("      });");
  lines.push("");
  lines.push("      await expect(");
  lines.push("        page.getByText(new RegExp(templateCode, \"i\")).first(),");
  lines.push("      ).toBeVisible({ timeout: 20_000 });");
  lines.push("");
  lines.push("      const sectionHeadings = page.locator(\"h3\");");
  lines.push("      await expect(sectionHeadings.first()).toBeVisible({ timeout: 20_000 });");
  lines.push("      const sectionCount = await sectionHeadings.count();");
  lines.push("      expect(sectionCount).toBeGreaterThanOrEqual(1);");
  lines.push("");
  lines.push("      const inputs = page.locator(\"input, textarea, select\");");
  lines.push("      await expect(inputs.first()).toBeVisible({ timeout: 20_000 });");
  lines.push("      const inputCount = await inputs.count();");
  lines.push("      expect(inputCount).toBeGreaterThanOrEqual(1);");
  lines.push("");
  lines.push("      const previewBtn = page");
  lines.push("        .getByRole(\"button\", { name: /Xem trước bản in/i })");
  lines.push("        .first();");
  lines.push("      await expect(previewBtn).toBeVisible();");
  lines.push("");
  lines.push("      await expect(page.locator(\"text=Không tìm thấy trang\")).toHaveCount(0);");
  lines.push("");
  lines.push("      await expect(page.locator(\"text=Lịch sử xử lý\")).toHaveCount(0);");
  lines.push("");
  lines.push("      const fatal = [...consoleErrors, ...pageErrors].filter(");
  lines.push("        (m) =>");
  lines.push("          !/Clerk has been loaded with development keys/i.test(m) &&");
  lines.push("          !/infinite redirect loop/i.test(m) &&");
  lines.push("          !/Download the React DevTools/i.test(m) &&");
  lines.push("          !/Failed to load resource: the server responded with a status of 429/i.test(m) &&");
  lines.push("          !/ThrottlerException/i.test(m) &&");
  lines.push("          !/Too Many Requests/i.test(m),");
  lines.push("      );");
  lines.push("      expect(fatal, `console/page errors: ${fatal.join(\" | \")}`).toHaveLength(0);");
  lines.push("    });");
  lines.push("  }");
  lines.push("});");
  lines.push("");
  return lines.join("\n");
}

function fail(msg) {
  console.error(`FAIL: ${msg}`);
  process.exit(1);
}

function readJson(path, label) {
  if (!existsSync(path)) fail(`missing ${label}: ${path}`);
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch (err) {
    fail(`invalid JSON in ${label}: ${err.message}`);
  }
}

async function httpOk(url, timeoutMs = 4000) {
  const ctl = new AbortController();
  const timer = setTimeout(() => ctl.abort(), timeoutMs);
  try {
    const r = await fetch(url, { signal: ctl.signal });
    return r.ok || r.status === 304;
  } catch {
    return false;
  } finally {
    clearTimeout(timer);
  }
}

async function waitFor(url, label, timeoutMs = 180_000) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    if (await httpOk(url)) {
      console.log(`[browser-visibility] ${label} ready after ${Math.round((Date.now() - start) / 1000)}s`);
      return true;
    }
    await new Promise((r) => setTimeout(r, 1000));
  }
  return false;
}

function classifyFailure(errMsg, durationMs) {
  if (!errMsg) return "UNKNOWN";
  const e = String(errMsg);
  const throttling = classifyThrottlingEvidence({
    errorMessage: e,
    durationMs,
  });
  if (throttling.classification !== "UNVERIFIED") {
    return throttling.classification;
  }
  if (/sign-in|sign-up/i.test(e)) return "AUTH_FAIL";
  if (/404|not found/i.test(e)) return "ROUTE_404";
  if (/Timed out waiting|page\.goto|net::ERR_|net error|net::ABORTED/i.test(e)) return "ROUTE_RENDER_FAIL";
  if (/not visible|toBeVisible/i.test(e)) return "VISIBILITY_FAIL";
  if (/documents/i.test(e)) return "DOCUMENTS_ROUTE_LEAK";
  return "UNKNOWN";
}

function loadPlaywrightRun(jsonPath) {
  if (!existsSync(jsonPath)) {
    return { error: "no playwright json", stats: null, byCode: new Map() };
  }
  try {
    const buf = readFileSync(jsonPath);
    let raw;
    if (buf.length >= 2 && buf[0] === 0xff && buf[1] === 0xfe) {
      raw = buf.toString("utf16le");
      if (raw.charCodeAt(0) === 0xfeff) raw = raw.slice(1);
    } else {
      raw = buf.toString("utf8");
      if (raw.charCodeAt(0) === 0xfeff) raw = raw.slice(1);
    }
    const anchor = raw.indexOf('"config":');
    if (anchor < 0) {
      return { error: "no playwright json", stats: null, byCode: new Map() };
    }
    let start = -1;
    for (let i = anchor; i >= 0; i--) {
      if (raw[i] === "{") {
        start = i;
        break;
      }
    }
    if (start < 0) {
      return { error: "no opening brace", stats: null, byCode: new Map() };
    }
    let depth = 0;
    let end = -1;
    let inStr = false;
    let escape = false;
    for (let i = start; i < raw.length; i++) {
      const c = raw[i];
      if (inStr) {
        if (escape) escape = false;
        else if (c === "\\") escape = true;
        else if (c === '"') inStr = false;
        continue;
      }
      if (c === '"') { inStr = true; continue; }
      if (c === "{") depth++;
      else if (c === "}") {
        depth--;
        if (depth === 0) {
          end = i + 1;
          break;
        }
      }
    }
    if (end < 0) {
      return { error: "no matching close brace", stats: null, byCode: new Map() };
    }
    const data = JSON.parse(raw.slice(start, end));
    const byCode = new Map();
    function walk(suites) {
      for (const s of suites ?? []) {
        for (const spec of s.specs ?? []) {
          const m = /BM-\d+\b/.exec(spec.title);
          if (!m) continue;
          const code = m[0];
          for (const t of spec.tests ?? []) {
            const r = t.results?.[t.results.length - 1];
            byCode.set(code, {
              templateCode: code,
              specTitle: spec.title,
              specFile: spec.file,
              status: r?.status ?? "unknown",
              durationMs: r?.duration ?? null,
              errorMessage: r?.error?.message ?? null,
            });
          }
        }
        walk(s.suites);
      }
    }
    walk(data.suites);
    return { stats: data.stats ?? null, byCode };
  } catch (err) {
    // Fallback: try parsing the largest prefix that closes brackets.
    // The naive counter above may mis-count braces inside escaped strings,
    // so attempt a progressive search from the start anchor.
    try {
      let lastGoodEnd = -1;
      let d = 0;
      let inStr = false;
      let escape = false;
      for (let i = start; i < raw.length; i++) {
        const c = raw[i];
        if (inStr) {
          if (escape) escape = false;
          else if (c === "\\") escape = true;
          else if (c === '"') inStr = false;
          continue;
        }
        if (c === '"') { inStr = true; continue; }
        if (c === "{") d++;
        else if (c === "}") {
          d--;
          if (d === 0) {
            try {
              const slice = raw.slice(start, i + 1);
              const candidate = JSON.parse(slice);
              const byCode = new Map();
              function walk(suites) {
                for (const s of suites ?? []) {
                  for (const spec of s.specs ?? []) {
                    const m = /BM-\d+\b/.exec(spec.title);
                    if (!m) continue;
                    const code = m[0];
                    for (const t of spec.tests ?? []) {
                      const r = t.results?.[t.results.length - 1];
                      byCode.set(code, {
                        templateCode: code,
                        specTitle: spec.title,
                        specFile: spec.file,
                        status: r?.status ?? "unknown",
                        durationMs: r?.duration ?? null,
                        errorMessage: r?.error?.message ?? null,
                      });
                    }
                  }
                  walk(s.suites);
                }
              }
              walk(candidate.suites);
              return { stats: candidate.stats ?? null, byCode };
            } catch {
              // not a valid endpoint, continue
            }
          }
        }
      }
    } catch (_) {}
    return {
      error: String(err?.message || err),
      stats: null,
      byCode: new Map(),
    };
  }
}

