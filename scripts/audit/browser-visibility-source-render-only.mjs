#!/usr/bin/env node
/**
 * Source/Render-Only Browser Visibility Smoke orchestrator.
 *
 * PHASE 2 — Local-only browser visibility smoke for source/render-only
 * INPUT_CONNECTED_PASS forms that have not yet had browser evidence.
 *
 * Responsibilities:
 *   1. Read the candidate codes from
 *      docs/audit/unified-bm-workspace/QLLAW_SOURCE_RENDER_ONLY_BROWSER_VISIBILITY_CANDIDATES.latest.json
 *   2. Generate a data-driven Playwright spec at
 *      tests/e2e/source-render-only-browser-visibility.auth.spec.ts
 *   3. Wait for the web dev server to be ready (or fail with NEED_USER_DECISION)
 *   4. Run the Playwright spec via the existing authenticated chromium project
 *      (uses existing Clerk ticket storage state at playwright/.clerk/admin.json)
 *   5. Parse the Playwright JSON output into a deterministic per-form artifact
 *      at docs/audit/unified-bm-workspace/QLLAW_SOURCE_RENDER_ONLY_BROWSER_VISIBILITY.latest.json
 *
 * Hard rules:
 *   - Does NOT click demo / preview / download DOCX.
 *   - Does NOT mutate the matrix, source DOCX, normalized DOCX, locked or
 *     compiled contracts, DB rows, Prisma schema, migrations, or API route
 *     paths.
 *   - Does NOT promote FormFlight runtimeReady allowlist.
 *   - Does NOT set fidelityComplete=true or FIDELITY_COMPLETE_EVIDENCED.
 *   - Does NOT log env values, cookies, tokens, storageState contents.
 *
 * Usage:
 *   node scripts/audit/browser-visibility-source-render-only.mjs
 */

