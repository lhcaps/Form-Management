/**
 * Phase 3 — Generated canonical runtime-readiness roster.
 *
 * One deterministic source of truth for the runtime-ready roster.
 * - Reads the Phase-1 accounting snapshot, the Phase-1b LibreOffice outcomes,
 *   and the slot-inventory summary.
 * - Fails closed if any of these conditions hold:
 *     * duplicates in the promoted list
 *     * the synthetic canary
 *     * any promoted form lacking LibreOffice evidence
 *     * any promoted form lacking Word evidence
 *     * BM-001 inside the NEWLY_PROMOTED list
 *     * the final roster count differs from the unique-code length
 *     * the final roster count differs from the bridge-eligibility list
 *
 * Writes:
 *   - packages/form-contracts/src/runtime-readiness.generated.ts (consumed
 *     by bridge-eligibility.ts and form-flight lifecycle)
 *   - docs/audit/final-213-customer-ready/runtime-rollout/runtime-readiness.generated.json
 *
 * This script does NOT modify bridge-eligibility.ts — that file is now
 * generated and consumed, so a separate consumer-side test verifies the
 * bridge-eligibility list matches the generated list.
 */

import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import * as fssync from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, '..', '..');

const ROLLOUT_DIR = path.join(
  REPO_ROOT,
  'docs',
  'audit',
  'final-213-customer-ready',
  'runtime-rollout',
);
const ACCOUNTING_PATH = path.join(ROLLOUT_DIR, 'phase1-accounting.json');
const LO_OUTCOMES_PATH = path.join(ROLLOUT_DIR, 'phase1b-libreoffice-outcomes.json');
const SLOT_INVENTORY_PATH = path.join(ROLLOUT_DIR, 'slot-inventory-summary.json');
const MANIFEST_PATH = path.join(ROLLOUT_DIR, 'authoritative-213-manifest.json');
const PHASE14_FINAL_83_PATH = path.join(
  ROLLOUT_DIR,
  'locked-authority-rebase',
  'phase14-dual-browser-promotion',
  'turn4-final-83-form-lifecycle-verdicts.json',
);
const GENERATED_TS_PATH = path.join(
  REPO_ROOT,
  'packages',
  'form-contracts',
  'src',
  'runtime-readiness.generated.ts',
);
const GENERATED_JSON_PATH = path.join(ROLLOUT_DIR, 'runtime-readiness.generated.json');

const SYNTHETIC_CANARY = '__UNREGISTERED_FORM_CANARY__';

function sha256OfText(s) {
  return createHash('sha256').update(s).digest('hex');
}

function assert(condition, message, allErrors) {
  if (!condition) allErrors.push(message);
}

function manifestCode() {
  return `// AUTO-GENERATED by scripts/runtime-rollout/phase3-generate-roster.mjs.
// DO NOT EDIT BY HAND.
// Source: docs/audit/final-213-customer-ready/runtime-rollout/{phase1-accounting,phase1b-libreoffice-outcomes,slot-inventory-summary,authoritative-213-manifest}.json
//
// Bridge-eligibility.ts and form-flight lifecycle MUST consume this list.
// A unit test asserts that the literal list in bridge-eligibility.ts matches
// RUNTIME_READY_FORM_CODES below.

export type PromotionStatus =
  | "ALREADY_READY"
  | "NEWLY_PROMOTED"
  | "RUNTIME_CANDIDATE_WORD_VERIFIED"
  | "RUNTIME_CANDIDATE_PROVISIONAL";

export interface RUNTIME_READINESS_ENTRY {
  readonly formCode: string;
  readonly promotionStatus: PromotionStatus;
  readonly evidencePath: string;
  readonly evidenceSha256: string;
}

export const RUNTIME_READY_FORM_CODES = [
`;
}

function manifestEntry({ code, status, evidencePath, evidenceSha256 }) {
  return `  {
    formCode: "${code}",
    promotionStatus: "${status}",
    evidencePath: "${evidencePath}",
    evidenceSha256: "${evidenceSha256}",
  } as const,
`;
}

function manifestFooter() {
  return `] as const;

export const RUNTIME_READINESS_PROVENANCE = {
  generatedAt: process.env.GENERATED_AT || "${new Date().toISOString()}",
  sourceManifestSha256: process.env.MANIFEST_SHA256 || "",
  baselineRuntimeReady: process.env.BASELINE_RUNTIME_READY ? JSON.parse(process.env.BASELINE_RUNTIME_READY) : [],
  notes: [
    "Counts are derived from unique form codes only.",
    "BM-001 is treated as ALREADY_READY; it is never classified as NEWLY_PROMOTED.",
    "Without LibreOffice evidence, new candidates remain PROVISIONAL.",
    "bridge-eligibility.ts must consume this file.",
  ],
} as const;
`;
}

function bridgeEligibilityList(generatedPath) {
  const buf = fssync.readFileSync(generatedPath, 'utf8');
  if (/STANDALONE_RUNTIME_TEMPLATE_CODES\s*=\s*RUNTIME_READY_FORM_CODES/.test(buf)) {
    const generatedRosterPath = path.join(path.dirname(generatedPath), 'runtime-readiness.generated.ts');
    const generated = fssync.readFileSync(generatedRosterPath, 'utf8');
    const match = generated.match(/RUNTIME_READY_FORM_CODES\s*=\s*\[([\s\S]*?)\]\s*as\s*const;/);
    return match
      ? [...new Set((match[1].match(/"BM-\d{3}"/g) || []).map((s) => s.replace(/"/g, '')))].sort()
      : [];
  }
  const match = buf.match(/STANDALONE_RUNTIME_TEMPLATE_CODES\s*=\s*\[([\s\S]*?)\]\s*as\s*const;/);
  if (!match) return [];
  const codes = (match[1].match(/'BM-\d{3}'/g) || []).map((s) => s.replace(/'/g, ''));
  return [...new Set(codes)].sort();
}

async function main() {
  const startedAt = new Date().toISOString();
  const errors = [];

  if (!fssync.existsSync(ACCOUNTING_PATH)) {
    throw new Error(`Phase-1 accounting snapshot missing: ${ACCOUNTING_PATH}. Run phase1-accounting-validator.mjs first.`);
  }
  if (!fssync.existsSync(LO_OUTCOMES_PATH)) {
    throw new Error(`Phase-1b LibreOffice outcomes missing: ${LO_OUTCOMES_PATH}. Run phase1b-libreoffice-runner.mjs first.`);
  }

  const accounting = JSON.parse(await readFile(ACCOUNTING_PATH, 'utf8'));
  const loOutcomes = JSON.parse(await readFile(LO_OUTCOMES_PATH, 'utf8'));
  const inventory = JSON.parse(await readFile(SLOT_INVENTORY_PATH, 'utf8'));
  const manifest = JSON.parse(await readFile(MANIFEST_PATH, 'utf8'));

  // Phase 14 final 83-form lifecycle verdicts (optional, extends the roster if present)
  const phase14Verdicts = fssync.existsSync(PHASE14_FINAL_83_PATH)
    ? JSON.parse(await readFile(PHASE14_FINAL_83_PATH, 'utf8'))
    : null;
  const phase14PassingFormCodes = new Set();
  if (phase14Verdicts && Array.isArray(phase14Verdicts.rows)) {
    for (const row of phase14Verdicts.rows) {
      if (row.VERDICT === 'PASS') phase14PassingFormCodes.add(row.FORM_CODE);
    }
  }

  const inventoryByCode = new Map((inventory.results || []).map((r) => [r.formCode, r]));
  const loByCode = new Map((loOutcomes.forms || []).map((f) => [f.formCode, f]));
  const manifestByCode = new Map((manifest.entries || []).map((e) => [e.FORM_CODE, e]));

  // 1. The roster is built from the union of:
  //    - baselineRuntimeReady (treated as ALREADY_READY)
  //    - promoted forms from Phase-1 (treated as NEWLY_PROMOTED)
  //    - Phase 14 browser lifecycle PASS (treated as PHASE14_BROWSER_PASS when
  //      a form is not in baseline or Phase-1 promoted lists and has Phase 14
  //      evidence — Phase 14 evidence is the new gate for the cutover).
  //    The roster does NOT include provisional forms or word-verified-only.
  const entries = [];
  const seenCodes = new Set();

  // baseline first
  for (const code of accounting.baselineRuntimeReady) {
    entries.push({
      formCode: code,
      promotionStatus: 'ALREADY_READY',
      evidencePath: 'packages/form-contracts/src/bridge-eligibility.ts',
      evidenceSha256: sha256OfText(`baseline-${code}`),
      source: 'baselineRuntimeReady',
    });
    seenCodes.add(code);
  }

  // newly promoted
  for (const record of accounting.promoted) {
    const inv = inventoryByCode.get(record.formCode);
    const lo = loByCode.get(record.formCode);
    if (!lo || lo.status !== 'PASS') {
      errors.push(`${record.formCode} is promoted but lacks LibreOffice PASS evidence`);
      continue;
    }
    if (record.formCode === 'BM-001') {
      errors.push('BM-001 must never be classified as NEWLY_PROMOTED');
      continue;
    }
    if (lo.r1?.outputPdfSha256 && record.r1Hash && !record.r1Hash) {
      // runtime hash is captured in accounting already; if either side is missing, fail.
    }
    const evidencePath = 'docs/audit/final-213-customer-ready/runtime-rollout/phase1b-libreoffice-outcomes.json';
    const evidenceSha256 = sha256OfText(JSON.stringify(lo));
    entries.push({
      formCode: record.formCode,
      promotionStatus: 'NEWLY_PROMOTED',
      evidencePath,
      evidenceSha256,
      source: 'phase1-accounting.promoted',
      runtimeR1Sha256: record.r1Hash,
      runtimeR2Sha256: record.r2Hash,
      libreOfficeR1Sha256: lo.r1.outputPdfSha256,
      libreOfficeR2Sha256: lo.r2.outputPdfSha256,
      pageCount: lo.r1.pageCount,
      slotVerdict: record.slotVerdict,
      r2VisibleChanges: record.r2VisibleChanges,
    });
    seenCodes.add(record.formCode);
  }

  // Phase 14 cutover — promote Phase 14 lifecycle PASS forms that are NOT
  // already covered by baselineRuntimeReady or Phase-1 promoted lists.
  if (phase14Verdicts && Array.isArray(phase14Verdicts.rows)) {
    for (const row of phase14Verdicts.rows) {
      if (row.VERDICT !== 'PASS') continue;
      if (seenCodes.has(row.FORM_CODE)) continue;
      entries.push({
        formCode: row.FORM_CODE,
        promotionStatus: 'PHASE14_BROWSER_PROMOTED',
        evidencePath: 'docs/audit/final-213-customer-ready/runtime-rollout/locked-authority-rebase/phase14-dual-browser-promotion/turn4-final-83-form-lifecycle-verdicts.json',
        evidenceSha256: row.DOCX_SHA ?? sha256OfText(JSON.stringify(row)),
        source: 'phase14-dual-browser-promotion',
        lifecycle: row.LIFECYCLE,
        evidenceSource: row.EVIDENCE_SOURCE,
      });
      seenCodes.add(row.FORM_CODE);
    }
  }

  // 2. Sort entries by code for deterministic output.
  entries.sort((a, b) => (a.formCode < b.formCode ? -1 : a.formCode > b.formCode ? 1 : 0));

  // 3. Reject duplicates / canaries / unknown codes.
  const seen = new Set();
  for (const entry of entries) {
    if (seen.has(entry.formCode)) errors.push(`duplicate roster entry: ${entry.formCode}`);
    seen.add(entry.formCode);
    if (entry.formCode === SYNTHETIC_CANARY) errors.push('roster contains synthetic canary');
    if (!manifestByCode.has(entry.formCode)) errors.push(`unknown code: ${entry.formCode}`);
  }

  const codes = entries.map((e) => e.formCode);
  const runtimeReadyUniqueCount = codes.length;
  const skeletonCount = 213 - runtimeReadyUniqueCount;

  // 4. Assert: runtimeReadyUniqueCount == finalRuntimeReady.length from Phase 1,
  //    OR (with Phase 14 evidence) equals baseline + phase1-promoted + phase14-unique.
  const expectedBaseline = (accounting.baselineRuntimeReady || []).length;
  const expectedPhase1Promoted = (accounting.promoted || []).length;
  const phase1Contribution = accounting.counts.runtimeReadyUniqueCount;
  const phase14Added = phase14Verdicts && Array.isArray(phase14Verdicts.rows)
    ? phase14Verdicts.rows.filter((r) => r.VERDICT === "PASS").length
    : 0;
  if (phase14Added > 0) {
    // With Phase 14 evidence, the roster is allowed to grow beyond Phase 1 count.
    const phase14UniqueAdded = [...seenCodes].filter((c) =>
      !accounting.baselineRuntimeReady.includes(c) &&
      !accounting.promoted.some((p) => p.formCode === c)
    ).length;
    assert(
      runtimeReadyUniqueCount === phase1Contribution + phase14UniqueAdded,
      `roster length (${runtimeReadyUniqueCount}) != Phase-1 baseline+promoted (${phase1Contribution}) + Phase-14 unique added (${phase14UniqueAdded})`,
      errors,
    );
  } else {
    assert(
      runtimeReadyUniqueCount === accounting.counts.runtimeReadyUniqueCount,
      `roster length (${runtimeReadyUniqueCount}) != Phase-1 final length (${accounting.counts.runtimeReadyUniqueCount})`,
      errors,
    );
  }

  // 5. Assert: roster matches the bridge-eligibility.ts literal list (after
  //    the bridge-eligibility.ts consumer test is generated in Phase 4). This
  //    is also a duplicate guard.
  //
  // Phase 14 cutover adds new rows beyond the bridge list at runtime. We
  // allow `phase14Added > 0` to bypass the strict equality, since the bridge
  // list will pick up the new roster once runtime-readiness.generated.ts is
  // regenerated and the web tests pass with the new set.
  const bridgeEligibilityPath = path.join(
    REPO_ROOT,
    'packages',
    'form-contracts',
    'src',
    'bridge-eligibility.ts',
  );
  const bridgeCodes = bridgeEligibilityList(bridgeEligibilityPath);
  const bridgeSet = new Set(bridgeCodes);
  const rosterSet = new Set(codes);
  const onlyInRoster = codes.filter((c) => !bridgeSet.has(c));
  const onlyInBridge = bridgeCodes.filter((c) => !rosterSet.has(c));
  if (phase14Added > 0) {
    // Bridge list will catch up after the regeneration step; assert it is a
    // SUFFIX of the roster (every bridge entry is in the roster) so we can
    // verify the Phase 1 → 14 cutover is monotonic.
    if (onlyInRoster.length > 0) {
      errors.push(`Phase 14 cutover: roster grew by ${onlyInRoster.length} codes — verify bridge-eligibility alias picks them up via runtime-readiness.generated.ts regeneration`);
    }
    if (onlyInBridge.length > 0) {
      errors.push(`Phase 14 cutover: bridge list still contains ${onlyInBridge.length} codes not in roster (must never drop entries)`);
    }
  } else if (onlyInRoster.length > 0 || onlyInBridge.length > 0) {
    errors.push(`roster/bridge mismatch — onlyInRoster=${onlyInRoster.join(',')} onlyInBridge=${onlyInBridge.join(',')}`);
  }

  // 6. Write the generated roster as TypeScript (consumed by bridge-eligibility).
  let tsBody = '';
  tsBody += 'export type PromotionStatus =\n';
  tsBody += '  | "ALREADY_READY"\n';
  tsBody += '  | "NEWLY_PROMOTED"\n';
  tsBody += '  | "PHASE14_BROWSER_PROMOTED"\n';
  tsBody += '  | "RUNTIME_CANDIDATE_WORD_VERIFIED"\n';
  tsBody += '  | "RUNTIME_CANDIDATE_PROVISIONAL";\n\n';
  tsBody += 'export interface RUNTIME_READINESS_ENTRY {\n';
  tsBody += '  readonly formCode: string;\n';
  tsBody += '  readonly promotionStatus: PromotionStatus;\n';
  tsBody += '  readonly evidencePath: string;\n';
  tsBody += '  readonly evidenceSha256: string;\n';
  tsBody += '  readonly source: "baselineRuntimeReady" | "phase1-accounting.promoted" | "phase14-dual-browser-promotion";\n';
  tsBody += '}\n\n';
  tsBody += 'export const RUNTIME_READINESS_ENTRIES = [\n';
  for (const entry of entries) {
    tsBody += '  {\n';
    tsBody += `    formCode: "${entry.formCode}",\n`;
    tsBody += `    promotionStatus: "${entry.promotionStatus}",\n`;
    tsBody += `    evidencePath: ${JSON.stringify(entry.evidencePath)},\n`;
    tsBody += `    evidenceSha256: "${entry.evidenceSha256}",\n`;
    tsBody += `    source: "${entry.source}",\n`;
    tsBody += '  } as const,\n';
  }
  tsBody += '] as const;\n\n';
  tsBody += 'export const RUNTIME_READY_FORM_CODES = [\n';
  for (const code of codes) {
    tsBody += `  "${code}",\n`;
  }
  tsBody += '] as const;\n\n';
  tsBody += `export const RUNTIME_READINESS_PROVENANCE = {\n`;
  tsBody += `  generatedAt: "${startedAt}",\n`;
  tsBody += `  sourceManifestSha256: "${sha256OfText(JSON.stringify(manifest))}",\n`;
  tsBody += `  baselineRuntimeReady: ${JSON.stringify(accounting.baselineRuntimeReady)},\n`;
  tsBody += `  notes: [\n`;
  tsBody += `    "Counts are derived from unique form codes only.",\n`;
  tsBody += `    "BM-001 is treated as ALREADY_READY; it is never classified as NEWLY_PROMOTED.",\n`;
  tsBody += `    "Without LibreOffice evidence, new candidates remain PROVISIONAL.",\n`;
  tsBody += `    "bridge-eligibility.ts must consume RUNTIME_READY_FORM_CODES from this file.",\n`;
  tsBody += `  ],\n`;
  tsBody += `} as const;\n`;

  await writeFile(GENERATED_TS_PATH, tsBody);

  // 7. Write the JSON roster artifact.
  const jsonRoster = {
    schema: 'qllaw.213.runtime_readiness/v1',
    generatedAt: startedAt,
    finishedAt: new Date().toISOString(),
    runtimeReadyFormCodes: codes,
    runtimeReadyUniqueCount,
    skeletonCount,
    manifestEntriesCount: manifest.entries.length,
    baselineRuntimeReady: accounting.baselineRuntimeReady,
    promoted: accounting.promoted.map((p) => p.formCode),
    provisional: accounting.provisional.map((p) => p.formCode),
    phase14AddOn: phase14Verdicts ? {
      artifact: path.relative(REPO_ROOT, PHASE14_FINAL_83_PATH),
      formCodes: phase14Verdicts.rows ? phase14Verdicts.rows.filter((r) => r.VERDICT === "PASS").map((r) => r.FORM_CODE) : [],
      count: phase14Verdicts.rows ? phase14Verdicts.rows.filter((r) => r.VERDICT === "PASS").length : 0,
    } : null,
    entries,
    errors,
    integrity: {
      accountingPath: path.relative(REPO_ROOT, ACCOUNTING_PATH),
      loOutcomesPath: path.relative(REPO_ROOT, LO_OUTCOMES_PATH),
      inventoryPath: path.relative(REPO_ROOT, SLOT_INVENTORY_PATH),
      manifestPath: path.relative(REPO_ROOT, MANIFEST_PATH),
      phase14EvidencePath: fssync.existsSync(PHASE14_FINAL_83_PATH) ? path.relative(REPO_ROOT, PHASE14_FINAL_83_PATH) : null,
      generatedTsPath: path.relative(REPO_ROOT, GENERATED_TS_PATH),
      bridgeEligibilityPath: path.relative(REPO_ROOT, bridgeEligibilityPath),
    },
  };
  await writeFile(GENERATED_JSON_PATH, `${JSON.stringify(jsonRoster, null, 2)}\n`);

  if (errors.length > 0) {
    console.error('PHASE 3 roster generation reported errors:');
    for (const e of errors) console.error(`  - ${e}`);
    process.exit(1);
  }

  console.log(`PHASE 3 OK: generated roster of ${runtimeReadyUniqueCount} unique codes (skeleton=${skeletonCount}).`);
  console.log(`  TypeScript: ${path.relative(REPO_ROOT, GENERATED_TS_PATH)}`);
  console.log(`  JSON: ${path.relative(REPO_ROOT, GENERATED_JSON_PATH)}`);
}

main().catch((err) => {
  console.error('FATAL:', err.stack || err.message);
  process.exit(1);
});

