#!/usr/bin/env node
/**
 * Generates the React registry and metadata-only registry from the same
 * component records. Generation fails when either does not match the locked
 * contract corpus.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoPath = (...segments) => path.resolve(__dirname, "..", ...segments);
const componentsDir = repoPath("apps", "web", "src", "components", "documents");
const registryOutputPath = path.join(componentsDir, "bm-panel-registry.generated.ts");
const metadataOutputPath = repoPath(
  "apps",
  "web",
  "src",
  "lib",
  "generated",
  "bm-panel-codes.generated.ts",
);
const lockedContractsDir = repoPath("docs", "audit", "docx", "contracts", "locked");

function componentName(code) {
  return `Bm${code.replace("BM-", "")}FormInputsPanel`;
}

function sortedEqual(actual, expected) {
  return actual.length === expected.length && actual.every((code, index) => code === expected[index]);
}

function assertCorpusEquality(name, actual, expected) {
  if (sortedEqual(actual, expected)) return;
  const actualSet = new Set(actual);
  const expectedSet = new Set(expected);
  const missing = expected.filter((code) => !actualSet.has(code));
  const unexpected = actual.filter((code) => !expectedSet.has(code));
  throw new Error(
    `${name} does not match locked contract keys. Missing: ${missing.join(", ") || "none"}; unexpected: ${unexpected.join(", ") || "none"}.`,
  );
}

const entries = fs
  .readdirSync(componentsDir)
  .filter((file) => /^bm-\d{3}-form-inputs\.tsx?$/.test(file))
  .sort()
  .map((file) => {
    const code = `BM-${file.match(/^bm-(\d{3})-form-inputs\.tsx?$/)[1]}`;
    const expectedExport = componentName(code);
    const source = fs.readFileSync(path.join(componentsDir, file), "utf8");
    const hasExpectedExport = new RegExp(
      `^export function ${expectedExport}\\b|^export const ${expectedExport}\\b`,
      "m",
    ).test(source);
    if (!hasExpectedExport) {
      throw new Error(`${file} must export ${expectedExport} for the generated registry.`);
    }
    return { code, file };
  });

const registeredCodes = entries.map((entry) => entry.code).sort();
const lockedContractCodes = [...new Set(
  fs.readdirSync(lockedContractsDir)
    .map((file) => file.match(/^(BM-\d{3})__/))
    .filter(Boolean)
    .map((match) => match[1]),
)].sort();

assertCorpusEquality("BM panel registry", registeredCodes, lockedContractCodes);

const registryLines = [
  "/**",
  " * Auto-generated by scripts/generate-bm-panel-registry.mjs.",
  " * The generator asserts equality with the locked-contract corpus.",
  " */",
  "",
  ...entries.map((entry) =>
    `import { ${componentName(entry.code)} } from \"./${entry.file.replace(/\.tsx?$/, "")}\";`,
  ),
  "",
  "export const BM_PANEL_REGISTRY: Record<string, React.ComponentType<{",
  "  documentId: string;",
  "  onSaved?: () => void;",
  "}>> = {",
  ...entries.map((entry) => `  \"${entry.code}\": ${componentName(entry.code)},`),
  "};",
  "",
  `export const BM_PANEL_COUNT = ${registeredCodes.length};`,
  "export const MISSING_BM_PANELS: readonly string[] = [];",
];

const metadataLines = [
  "/** Auto-generated by scripts/generate-bm-panel-registry.mjs. */",
  "export const REGISTERED_BM_PANEL_CODES = [",
  ...registeredCodes.map((code) => `  \"${code}\",`),
  "] as const;",
  "",
  "const REGISTERED_BM_PANEL_CODE_SET = new Set<string>(REGISTERED_BM_PANEL_CODES);",
  "",
  "export function hasRegisteredBmPanel(templateCode: string): boolean {",
  "  return REGISTERED_BM_PANEL_CODE_SET.has(templateCode);",
  "}",
  "",
  `export const REGISTERED_BM_PANEL_COUNT = ${registeredCodes.length};`,
];

fs.writeFileSync(registryOutputPath, registryLines.join("\n"), "utf8");
fs.mkdirSync(path.dirname(metadataOutputPath), { recursive: true });
fs.writeFileSync(metadataOutputPath, metadataLines.join("\n"), "utf8");

console.log(`Generated ${registryOutputPath}`);
console.log(`Generated ${metadataOutputPath}`);
console.log(`Panels/locked contracts: ${registeredCodes.length}/${lockedContractCodes.length}`);
